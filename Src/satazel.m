function [azel] = satazel(rs, rr)
% ==============================================================================
% SATAZEL Compute satellite azimuth and elevation angles
% ------------------------------------------------------------------------------
% Inputs:
% ------------------------------------------------------------------------------
% Outputs:
% ------------------------------------------------------------------------------
% References:
%   -
% ------------------------------------------------------------------------------
% Author:
%   Cheolsoon Lim (csleem@sju.ac.kr)
% ------------------------------------------------------------------------------
% History:
%   -
% ==============================================================================

global const

nsat = size(rs, 1);
azel = [zeros(nsat, 1), pi/2*ones(nsat, 1)];

llh = xyz2llh(rr);

if (llh(3) > -const.RE_WGS84)
    enu = xyz2enu(rs, rr);
    
    azel(:,1) = atan2(enu(:,1), enu(:,2));
    azel(:,2) = atan2(enu(:,3), sqrt(enu(:,1).^2 + enu(:,2).^2));
    
    azel(azel(:,1) < 0, 1) = azel(azel(:,1) < 0, 1) + 2*pi;
end
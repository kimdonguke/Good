function [time] = gpst2time(week, tow)
% ==============================================================================
% GPST2TIME Convert week and tow in GPS time to standard time
% ------------------------------------------------------------------------------
% Inputs:
%   week <n x 1 matrix> : GPS week number [weeks]
%   
%   tow <n x 1 matrix> : GPS time of week [s]
% ------------------------------------------------------------------------------
% Outputs:
%   time <n x 1 matrix> : Standard time [s]
% ------------------------------------------------------------------------------
% References:
%   -
% ------------------------------------------------------------------------------
% Author:
%   Cheolsoon Lim (csleem@sju.ac.kr)
% ------------------------------------------------------------------------------
% History:
%   -
% ==============================================================================

time = cal2time([1980, 1, 6, 0, 0, 0]) + week*7 * 86400 + tow;
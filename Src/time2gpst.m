function [week, tow] = time2gpst(time)
% ==============================================================================
% TIME2GPST Convert standard time to week and tow in GPS time
% ------------------------------------------------------------------------------
% Inputs:
%   time <n x 1 matrix> : Standard time [s]
% ------------------------------------------------------------------------------
% Outputs:
%   week <n x 1 matrix> : GPS week number [weeks]
%   
%   tow <n x 1 matrix> : GPS time of week [s]
% ------------------------------------------------------------------------------
% References:
%   -
% ------------------------------------------------------------------------------
% Author:
%   Cheolsoon Lim (csleem@sju.ac.kr)
% ------------------------------------------------------------------------------
% History:
%   -
% ==============================================================================

sec  = time - cal2time([1980, 1, 6, 0, 0, 0]);
week = floor(sec / (86400 * 7));
tow  = sec - week * 86400 * 7;
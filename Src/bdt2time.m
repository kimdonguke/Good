function [time] = bdt2time(week, tow)
% ==============================================================================
% BDT2TIME Convert week and tow in BDS time to standard time
% ------------------------------------------------------------------------------
% Inputs:
%   week <n x 1 matrix> : BDS week number [weeks]
%   
%   tow <n x 1 matrix> : BDS time of week [s]
% ------------------------------------------------------------------------------
% Outputs:
%   time <n x 1 matrix> : Standard time [s]
% ------------------------------------------------------------------------------
% References:
%   -
% ------------------------------------------------------------------------------
% Author:
%   Cheolsoon Lim (csleem@sju.ac.kr)
% ------------------------------------------------------------------------------
% History:
%   -
% ==============================================================================

time = cal2time([2006, 1, 1, 0, 0, 0]) + week*7 * 86400 + tow;
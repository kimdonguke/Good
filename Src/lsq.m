function [dx, Q] = lsq(y, H, W)
% ==============================================================================
% lsq Least square estimation
% ------------------------------------------------------------------------------
% Inputs:
% ------------------------------------------------------------------------------
% Outputs:
% ------------------------------------------------------------------------------
% References:
%   -
% ------------------------------------------------------------------------------
% Author:
%   Cheolsoon Lim (csleem@sju.ac.kr)
% ------------------------------------------------------------------------------
% History:
%   -
% ==============================================================================

dx = (H'*W*H)\(H'*W)*y;
Q  = inv(H'*W*H);
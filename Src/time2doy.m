function [doy] = time2doy(time)
% ==============================================================================
% TIME2DOY Convert standard time to day of year
% ------------------------------------------------------------------------------
% Inputs:
% ------------------------------------------------------------------------------
% Outputs:
% ------------------------------------------------------------------------------
% References:
%   -
% ------------------------------------------------------------------------------
% Author:
%   Cheolsoon Lim (csleem@sju.ac.kr)
% ------------------------------------------------------------------------------
% History:
%   -
% ==============================================================================

cal = time2cal(time);
cal = [cal(1), 1, 1, 0, 0, 0];
doy = floor((time - cal2time(cal)) ./ 86400) + 1;
function [week, tow] = time2bdt(time)
% ==============================================================================
% TIME2BDT Convert standard time to week and tow in BDS time
% ------------------------------------------------------------------------------
% Inputs:
%   time <n x 1 matrix> : Standard time [s]
% ------------------------------------------------------------------------------
% Outputs:
%   week <n x 1 matrix> : BDS week number [weeks]
%   
%   tow <n x 1 matrix> : BDS time of week [s]
% ------------------------------------------------------------------------------
% References:
%   -
% ------------------------------------------------------------------------------
% Author:
%   Cheolsoon Lim (csleem@sju.ac.kr)
% ------------------------------------------------------------------------------
% History:
%   -
% ==============================================================================

sec  = time - cal2time([2006, 1, 1, 0, 0, 0]);
week = floor(sec / (86400 * 7));
tow  = sec - week * 86400 * 7;